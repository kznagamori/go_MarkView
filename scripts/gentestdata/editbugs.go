// editbugs.go — generated/edit/ に置く、v1.1.0 から残る不具合を確かめる文書と、その期待値（E2E-012 の表）。
//
//   - history/a.md〜d.md: 見出しの無い 1 行の文書（E2E-262 の手順 4〜8。BUG-023。E2E-251 の見出しの無い文書）
//   - footnote-task.md: 脚注の中のタスク（E2E-383 の手順 9〜11。BUG-027 の調査報告の 1.1 の 3 つの形）
//   - footnote-table.md: 脚注の中の表（E2E-384 の手順 20・21。BUG-027）
//
// **v1.2.0 の修正を入れる前に、v1.1.0 の配布物で症状を確かめるためにも使う**（90.6.5 の「修正の前に
// 実際に起きる」）。修正の後も同じ文書と同じ手順で確かめられるよう、手作りのファイルにしない。
//
// expected/ の 2 つは**人が書いたリテラル**である（editdata.go の冒頭と同じ。書き換えの実装を呼んで
// 作らない）。

// historyFiles は history/ の 4 つの文書（E2E-262）。**見出しを置かない**——E2E-251 はこの文書を
// アウトラインの空の表示に使う。どれを表示しているかを本文の 1 行で見分けられるようにする。
func historyFiles() []editFile {
	names := []string{"a", "b", "c", "d"}
	files := make([]editFile, 0, len(names))

	for _, name := range names {
		files = append(files, editFile{
			path:    "history/" + name + ".md",
			content: "これは " + name + ".md です（見出しの無い 1 行の文書）。\n",
		})
	}

	return files
}

// footnoteTaskMD は footnote-task.md（E2E-383。BUG-027）。
//
// 調査報告の 1.1 の 3 つの形を 1 つにまとめる。上から:
//
//   - 本文の段落。参照は 1 → a → b の順
//   - 定義 [^1]（タスク入り）が本文のタスクより前にある（形 1）
//   - **参照されていない**定義 [^z]（タスク入り。画面に出ない）が本文のタスクより前にある（形 2）
//   - 本文のタスク A / B
//   - 定義 [^b]、[^a] の順（**参照は a → b、定義は b → a**。形 3）
//
// 定義の中のタスクは半角空白 4 つで字下げする（定義の続きの段落になる）。
//
// v1.1.0 の目印は、定義を最初の定義の位置にまとめた木（参照されていない定義を含み、定義の順）で
// task:0〜5（脚注 1 / 見えない / 脚注 b / 脚注 a / 本文 A / 本文 B）と数え、書き換える位置は脚注を
// 末尾へ移した後の木（本文 A / 本文 B / 脚注 1 / 脚注 a / 脚注 b）で数える。
const footnoteTaskMD = `本文[^1]と[^a]と[^b]

[^1]: 脚注 1:

    - [ ] 脚注 1 のタスク

[^z]: 使っていない脚注:

    - [ ] 見えないタスク

- [ ] 本文のタスク A
- [ ] 本文のタスク B

[^b]: 脚注 b:

    - [ ] 脚注 b のタスク

[^a]: 脚注 a:

    - [ ] 脚注 a のタスク
`

